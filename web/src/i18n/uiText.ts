export function uiText(text: string, language: Language): string {
  return language === 'en' ? (uiEnglish[text] ?? text) : text
}
// Translate application-generated market labels only; never rewrite user names or prompts.
export function marketText(text: string, language: Language): string {
  if (language === 'zh') return text
  if (Object.prototype.hasOwnProperty.call(uiEnglish, text))
    return uiEnglish[text]
  return text
    .replace(/放量\s*([\d.]+)\s*倍/g, 'Volume $1×')
    .replace(/持仓量增加\s*/g, 'OI increase ')
    .replace(/持仓量减少\s*/g, 'OI decrease ')
    .replace(/持仓量数据缺失或过期/g, 'Open-interest data is missing or stale')
    .replace(/突破数据缺失或过期/g, 'Breakout data is missing or stale')
    .replace(/资金费率/g, 'Funding rate')
    .replace(
      /(\d+) 个合约K线不可用，已标记数据不足。/g,
      'Candle data unavailable for $1 contracts; marked as insufficient data.'
    )
    .replace(/K线分析不可用[:：]\s*/g, 'Candle analysis unavailable: ')
}
export function localizedError(
  text: string | undefined,
  language: Language
): string {
  const translated = marketText(text || '', language)
  return language === 'en' && /[\u3400-\u9fff]/.test(translated)
    ? 'Data is unavailable. Please retry or check the service logs for details.'
    : translated
}
